// Refreshes src/constants/cities.js from Israel's official list of localities
// (Central Bureau of Statistics, published on data.gov.il). Run when needed:
//   node scripts/update-cities.js
const fs = require('fs');
const path = require('path');

const RESOURCE = '5c78e9fa-c2e2-4771-93ff-7f400a12f7ba';
const URL = `https://data.gov.il/api/3/action/datastore_search?resource_id=${RESOURCE}&limit=5000`;
const OUT = path.join(__dirname, '..', 'src', 'constants', 'cities.js');

(async () => {
  const res = await fetch(URL, { headers: { 'User-Agent': 'Mozilla/5.0' } });
  if (!res.ok) throw new Error(`data.gov.il answered ${res.status}`);
  const { result } = await res.json();
  const names = [...new Set(result.records.map(r => String(r['שם_ישוב'] || '').replace(/\s+/g, ' ').trim()).filter(Boolean))]
    .sort((a, b) => a.localeCompare(b, 'he'));
  if (names.length < 1000) throw new Error(`only ${names.length} localities came back — not updating`);

  const lines = [];
  let line = ' ';
  for (const n of names) {
    const item = ` ${JSON.stringify(n)},`;
    if (line.length + item.length > 110) { lines.push(line); line = ' '; }
    line += item;
  }
  lines.push(line);
  fs.writeFileSync(OUT, [
    `// Israel's localities (CBS list via data.gov.il, resource ${RESOURCE}),`,
    "// for the עיר field's suggestions (utils/cities.js).",
    '// Generated by scripts/update-cities.js — don\'t edit by hand.',
    'export const ISRAEL_CITIES = [',
    ...lines,
    '];',
    '',
  ].join('\n'));
  console.log(`${names.length} localities written to ${path.relative(process.cwd(), OUT)}`);
})().catch(e => { console.error(e.message); process.exit(1); });
